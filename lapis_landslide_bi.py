# Metrics

def compute_metrics(
    pred: np.ndarray,
    target: np.ndarray,
    active_mask: np.ndarray,
) -> dict:
    """
    Compute reconstruction metrics.

    Args:
        pred: predicted state (can be 2D frame or 3D sequence) - UNSCALED (original units)
        target: ground truth state - UNSCALED (original units)
        active_mask: boolean mask of active region (H, W)

    Returns:
        Dictionary of metrics
    """
    from scipy.ndimage import uniform_filter

    # Handle sequences by averaging metrics across time
    if pred.ndim == 3:
        T = pred.shape[0]
        metrics_list = [compute_metrics(pred[t], target[t], active_mask) for t in range(T)]
        return {k: np.mean([m[k] for m in metrics_list]) for k in metrics_list[0]}

    pred_flat = pred.ravel()
    target_flat = target.ravel()
    active_flat = active_mask.ravel()

    # Active region metrics (unscaled)
    if active_flat.sum() > 0:
        pred_active = pred_flat[active_flat]
        target_active = target_flat[active_flat]

        rmse_active = np.sqrt(np.mean((pred_active - target_active) ** 2))

        if np.std(target_active) > 1e-6:
            corr_active = np.corrcoef(pred_active, target_active)[0, 1]
        else:
            corr_active = 0.0
    else:
        rmse_active = corr_active = 0.0

    # SSIM
    def compute_ssim(x, y):
        L = max(x.max() - x.min(), y.max() - y.min(), 1e-6)
        c1 = (0.01 * L) ** 2
        c2 = (0.03 * L) ** 2
        mx = uniform_filter(x, 5)
        my = uniform_filter(y, 5)
        sx2 = uniform_filter(x ** 2, 5) - mx ** 2
        sy2 = uniform_filter(y ** 2, 5) - my ** 2
        sxy = uniform_filter(x * y, 5) - mx * my
        ssim_map = (2 * mx * my + c1) * (2 * sxy + c2) / ((mx ** 2 + my ** 2 + c1) * (sx2 + sy2 + c2))
        return np.mean(ssim_map)

    ssim = compute_ssim(pred.reshape(active_mask.shape), target.reshape(active_mask.shape))

    # NSE (Nash-Sutcliffe Efficiency)
    if active_flat.sum() > 0 and np.var(target_active) > 1e-12:
        nse = 1.0 - np.sum((pred_active - target_active) ** 2) / np.sum((target_active - np.mean(target_active)) ** 2)
    else:
        nse = 0.0

    abs_pred_active = np.abs(pred_active) if active_flat.sum() > 0 else np.array([])
    abs_target_active = np.abs(target_active) if active_flat.sum() > 0 else np.array([])

    # KGE' on |DoD|
    if abs_target_active.size > 0 and np.std(abs_target_active) > 1e-12 and np.mean(abs_target_active) > 1e-12 and np.mean(abs_pred_active) > 1e-12:
        r_abs_m = np.corrcoef(abs_pred_active, abs_target_active)[0, 1]
        beta_abs_m = np.mean(abs_pred_active) / np.mean(abs_target_active)
        gamma_abs = (np.std(abs_pred_active) / np.mean(abs_pred_active)) / (np.std(abs_target_active) / np.mean(abs_target_active))
        kge_prime_abs = 1.0 - np.sqrt((r_abs_m - 1) ** 2 + (beta_abs_m - 1) ** 2 + (gamma_abs - 1) ** 2)
    else:
        kge_prime_abs = 0.0

    result = {
        'rmse_active': rmse_active,
        'corr_active': corr_active,
        'ssim': ssim,
        'nse': nse,
        'kge_prime_abs': kge_prime_abs,
    }

    return result


