# SESSION LOGGING & TIMING

class Tee:
    """Duplicate stdout/stderr to both console and a log file."""
    def __init__(self, *streams):
        self.streams = streams
    def write(self, data):
        for s in self.streams:
            s.write(data); s.flush()
    def flush(self):
        for s in self.streams:
            s.flush()


class TimingLogger:
    """Track wall-clock time for named pipeline stages."""
    def __init__(self):
        self.timings = OrderedDict(); self._s = {}; self._t = None
    def start_total(self): self._t = time.time()
    def start(self, name): self._s[name] = time.time()
    def stop(self, name):
        if name in self._s: self.timings[name] = time.time() - self._s[name]
    def get_total(self): return time.time() - self._t if self._t else 0
    def fmt(self, d): return f"{int(d // 60)}m {d % 60:.1f}s" if d >= 60 else f"{d:.1f}s"
    def print_summary(self):
        print("\n" + "=" * 60)
        print("  TIMING SUMMARY")
        print("=" * 60)
        for s, d in self.timings.items():
            print(f"  {s:<45} {self.fmt(d):>12}")
        print("-" * 60)
        print(f"  {'TOTAL':<45} {self.fmt(self.get_total()):>12}")
        print("=" * 60)


