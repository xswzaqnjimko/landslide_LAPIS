def run_pipeline(config: Config):
    """Execute the full LAPIS pipeline for one scenario."""

    config.RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    config.MODELS_DIR.mkdir(parents=True, exist_ok=True)

    # ---- Session log ----
    log_path = config.RESULTS_DIR / f"log_{datetime.now():%Y%m%d_%H%M%S}.txt"
    log_f = open(log_path, 'w', buffering=1)
    sys.stdout = Tee(sys.__stdout__, log_f)
    sys.stderr = Tee(sys.__stderr__, log_f)

    timer = TimingLogger()
    timer.start_total()

    use_forward = (getattr(config, 'INFERENCE_MODE', 'backward').lower() == 'forward')

    print("=" * 70)
    print("  LAPIS-SHRED Landslide — Spatiotemporal Reconstruction")
    print("=" * 70)
    print(f"\n  Scenario: {config.SCENARIO_TAG}")
    print(f"  Inference mode: {'forward (windowed)' if use_forward else 'backward (terminal frame)'}")
    if config.METADATA:
        print(f"  Description: {config.METADATA.get('description', '')}")
        pr = config.METADATA.get('perturbation_range')
        pr_str = f"±{pr*100:.0f}%" if isinstance(pr, (int, float)) else "N/A"
        print(f"  Ensemble: {config.METADATA.get('n_ensemble', '?')} sims, "
              f"{pr_str} perturbation")
    print(f"  Data Dir: {config.DATA_DIR}")
    print(f"  Results Dir: {config.RESULTS_DIR}")

    rng = jax.random.PRNGKey(config.SEED)

    # Step 1: Load data
    print("\n[1] Loading Data...")
    timer.start("1. Data loading")

    topology = load_topology(config)
    dem = topology['dem']
    H, W = dem.shape
    print(f"  Grid size: {H}x{W}")

    train_thetas, test_theta = load_theta_configs(config)
    print(f"  Train thetas: {len(train_thetas)}")
    theta_str = (f"S_c={test_theta['S_c']:.4f}, q_c={test_theta['q_c']:.4f}, "
                 f"k={test_theta['k']:.5f}")
    if 'soil_depth' in test_theta:
        theta_str += (f", soil={test_theta['soil_depth']:.2f}, "
                      f"dp={test_theta['depth_parameter']:.2f}")
    print(f"  Test theta: {theta_str}")

    print("  Loading simulations...")
    train_dods, test_dod, keep_idx = load_all_simulations(config)
    T_test = test_dod.shape[0]

    if keep_idx is not None:
        train_thetas = [train_thetas[i] for i in keep_idx]

    print(f"  Loaded {len(train_dods)} training simulations + 1 ground truth")
    timer.stop("1. Data loading")

    # Step 2: Prepare sensors and dataset
    print("\n[2] Preparing Sensors and Dataset...")
    timer.start("2. Sensors & dataset")

    combined_active = np.any(
        np.concatenate([np.abs(d) > config.ACTIVE_THRESHOLD for d in train_dods], axis=0),
        axis=0
    )

    if config.SENSOR_PLACEMENT == "top":
        sensor_dod = train_dods[0][1]
    else:
        sensor_dod = train_dods[0][-1]
    sensors = place_sensors(dem, sensor_dod, config.N_SENSORS,
                            config.ACTIVE_THRESHOLD, config.SEED)
    print(f"  Placed {len(sensors)} sensors (placement: {config.SENSOR_PLACEMENT})")

    # Build dataset — padding depends on inference mode
    obs_len = None
    if use_forward:
        # Windowed observation: no padding
        dataset = EnsembleSeq2SeqDataset(train_dods, sensors, fit=True)
        obs_len = max(5, int(T_test * config.GT_OBS_FRACTION))
        print(f"  Dataset: {len(dataset)} sequences (no padding, windowed mode)")
        print(f"  Observation window: {obs_len} frames "
              f"({config.GT_OBS_FRACTION*100:.0f}% of GT T={T_test})")
    else:
        # Single terminal frame: end padding
        dataset = EnsembleSeq2SeqDataset(
            train_dods, sensors, end_pad=config.STATIC_PAD_LENGTH, fit=True)
        print(f"  Dataset: {len(dataset)} sequences (end_pad={config.STATIC_PAD_LENGTH})")

    print(f"  Sequence lengths (original): {dataset.T_originals}")
    print(f"  Sequence lengths (padded):   {dataset.T_padded}")

    save_initial_elevation(dem, combined_active, sensors, config, config.RESULTS_DIR / "initial_elevation.png")
    save_initial_elevation_zoomed(dem, combined_active, sensors, config, config.RESULTS_DIR / "initial_elevation_zoomed.png")
    timer.stop("2. Sensors & dataset")

    # Step 3: Train SHRED
    print("\n[3] Training SHRED...")
    timer.start("3. SHRED training")

    latent_dim = config.SEQ2SEQ_HIDDEN * 2
    print(f"  Architecture: {config.N_SENSORS} sensors -> BiLSTM(h={config.SEQ2SEQ_HIDDEN}) "
          f"-> latent_dim={latent_dim}")

    shred_model = Seq2SeqSHRED(
        n_sensors=config.N_SENSORS,
        hidden_size=config.SEQ2SEQ_HIDDEN,
        num_layers=config.NUM_LAYERS,
        state_dim=H * W,
        dropout_rate=config.DROPOUT_RATE
    )
    rng, shred_rng = jax.random.split(rng)
    shred_state = train_ensemble_shred(shred_model, dataset,
                                       combined_active, config, shred_rng)
    print("  Seq2Seq SHRED training complete.")
    timer.stop("3. SHRED training")

    # Step 4: Extract latent trajectories and train temporal model
    print(f"\n[4] Training {'Forward' if use_forward else 'Backward'} Model (LAPIS core)...")
    timer.start("4. Temporal model training")

    latent_trajectories, z_inits = extract_latent_trajectories_seq2seq(
        shred_state, dataset, config)
    T_originals = dataset.T_originals

    forward_state = None
    backward_state = None

    if use_forward:
        forward_model = ForwardFromWindow(
            latent_dim=latent_dim,
            hidden_dim=config.FORWARD_HIDDEN,
            num_layers=config.FORWARD_LAYERS,
            dropout_rate=config.DROPOUT_RATE
        )
        rng, forward_rng = jax.random.split(rng)
        forward_state = train_forward_model(
            forward_model, latent_trajectories, T_originals, obs_len, forward_rng,
            lr=config.LR_FORWARD, epochs=config.EPOCHS_FORWARD,
            lambda_recon=config.LAMBDA_RECON, lambda_anchor=config.LAMBDA_ANCHOR,
            lambda_shape=config.LAMBDA_SHAPE, weight_decay=config.WEIGHT_DECAY)
        print("  Forward model training complete.")
    else:
        backward_model = BackwardFromTerminal(
            latent_dim=latent_dim,
            hidden_dim=config.BACKWARD_HIDDEN,
            num_layers=config.BACKWARD_LAYERS,
            dropout_rate=config.DROPOUT_RATE
        )
        rng, backward_rng = jax.random.split(rng)
        backward_state = train_backward_model(
            backward_model, latent_trajectories, T_originals, obs_len, backward_rng,
            z_inits=z_inits,
            lr=config.LR_BACKWARD, epochs=config.EPOCHS_BACKWARD,
            lambda_recon=config.LAMBDA_RECON, lambda_anchor=config.LAMBDA_CONV,
            lambda_shape=config.LAMBDA_SHAPE, weight_decay=config.WEIGHT_DECAY)
        print("  Backward model training complete.")

    timer.stop("4. Temporal model training")

    # Step 5: SHRED demo reconstruction visualization
    print("\n[5] Generating SHRED Reconstruction Animations...")
    timer.start("5. SHRED reconstruction viz")

    shred_demo_idx = config.SHRED_DEMO_INDEX
    shred_demo_theta = train_thetas[shred_demo_idx] if train_thetas else test_theta
    shred_demo_gt = train_dods[shred_demo_idx]

    x_demo, _ = dataset[shred_demo_idx]
    pred_scaled_demo = shred_state.apply_fn(
        {'params': shred_state.params}, x_demo[None, ...], train=False)
    pred_demo_flat = dataset.scaler_states.inverse_transform(
        np.array(pred_scaled_demo[0]))
    # Strip padding from decoded output
    pre_offset = dataset.start_pad
    T_demo = dataset.T_originals[shred_demo_idx]
    pred_demo_flat = pred_demo_flat[pre_offset:pre_offset + T_demo]
    shred_demo_pred = pred_demo_flat.reshape(T_demo, H, W)
    shred_demo_active = np.any(np.abs(shred_demo_gt) > config.ACTIVE_THRESHOLD, axis=0)

    save_shred_video(shred_demo_gt, shred_demo_pred, shred_demo_active,
                     shred_demo_theta, config,
                     config.RESULTS_DIR / "shred", "shred_reconstruction")
    save_shred_video_logscale(shred_demo_gt, shred_demo_pred, shred_demo_active,
                              shred_demo_theta, config,
                              config.RESULTS_DIR / "shred", "shred_reconstruction_logscale")

    shred_end_frame = T_demo - 1
    save_zoomed_frame_figure(shred_demo_gt, shred_demo_pred, shred_demo_active,
                             shred_end_frame, "Forward SHRED (θ₁)", config,
                             config.RESULTS_DIR / "shred_reconstruction_zoomed_endframe.png")
    save_zoomed_frame_figure_logscale(
        shred_demo_gt, shred_demo_pred, shred_demo_active, shred_end_frame,
        "Forward SHRED (θ₁)", config,
        config.RESULTS_DIR / "shred_reconstruction_zoomed_endframe_logscale.png")

    shred_metrics_endframe = compute_metrics(
        shred_demo_pred[shred_end_frame:shred_end_frame + 1],
        shred_demo_gt[shred_end_frame:shred_end_frame + 1],
        shred_demo_active)
    save_combined_results_plot(
        shred_demo_gt[shred_end_frame], shred_demo_pred[shred_end_frame],
        shred_demo_active, sensors, train_thetas, shred_demo_theta,
        shred_metrics_endframe, config,
        config.RESULTS_DIR / "shred_combined_endframe.png",
        title_prefix="Forward SHRED")
    save_combined_results_plot_logscale(
        shred_demo_gt[shred_end_frame], shred_demo_pred[shred_end_frame],
        shred_demo_active, sensors, train_thetas, shred_demo_theta,
        shred_metrics_endframe, config,
        config.RESULTS_DIR / "shred_combined_endframe_logscale.png",
        title_prefix="Forward SHRED (Log Scale)")
    timer.stop("5. SHRED reconstruction viz")

    # Step 6: LAPIS Inference
    if use_forward:
        print(f"\n[6] LAPIS Forward Inference on Ground Truth (θ_test)...")
        timer.start("6. LAPIS inference")
        print(f"  Using first {obs_len} frames to predict remaining sequence...")

        pred_lapis = lapis_forward_inference_seq2seq(
            shred_state, forward_state, test_dod, sensors,
            dataset, obs_len, config)

        pred_shred = shred_baseline_seq2seq(
            shred_state, test_dod, sensors, dataset, config)

    else:
        print("\n[6] LAPIS Backward Inference on Ground Truth (θ_test)...")
        timer.start("6. LAPIS inference")
        print("  Using ONLY terminal frame to reconstruct full sequence...")

        pred_lapis = lapis_backward_inference_terminal_seq2seq(
            shred_state, backward_state, test_dod, sensors, dataset, config)

        pred_shred = shred_baseline_seq2seq(
            shred_state, test_dod, sensors, dataset, config)

    metrics_shred = compute_metrics(pred_shred, test_dod, combined_active)
    metrics_lapis = compute_metrics(pred_lapis, test_dod, combined_active)

    # ---- Per-frame metrics ----
    T_eval = min(pred_shred.shape[0], pred_lapis.shape[0], test_dod.shape[0])
    per_frame_nrmse_shred, per_frame_nrmse_lapis = [], []
    per_frame_ssim_shred, per_frame_ssim_lapis = [], []
    per_frame_nse_shred, per_frame_nse_lapis = [], []
    per_frame_kge_prime_abs_shred, per_frame_kge_prime_abs_lapis = [], []

    for t in range(T_eval):
        gt_t = test_dod[t]
        frame_gt_range = float(gt_t.max() - gt_t.min())

        m_shred_t = compute_metrics(pred_shred[t], gt_t, combined_active)
        m_lapis_t = compute_metrics(pred_lapis[t], gt_t, combined_active)

        nrmse_s = float(m_shred_t['rmse_active']) / frame_gt_range if frame_gt_range > 0 else 0.0
        nrmse_l = float(m_lapis_t['rmse_active']) / frame_gt_range if frame_gt_range > 0 else 0.0
        per_frame_nrmse_shred.append(nrmse_s)
        per_frame_nrmse_lapis.append(nrmse_l)
        per_frame_ssim_shred.append(float(m_shred_t['ssim']))
        per_frame_ssim_lapis.append(float(m_lapis_t['ssim']))
        per_frame_nse_shred.append(float(m_shred_t['nse']))
        per_frame_nse_lapis.append(float(m_lapis_t['nse']))
        per_frame_kge_prime_abs_shred.append(float(m_shred_t['kge_prime_abs']))
        per_frame_kge_prime_abs_lapis.append(float(m_lapis_t['kge_prime_abs']))

    overall_nrmse_shred = float(np.mean(per_frame_nrmse_shred))
    overall_nrmse_lapis = float(np.mean(per_frame_nrmse_lapis))
    overall_ssim_shred = float(np.mean(per_frame_ssim_shred))
    overall_ssim_lapis = float(np.mean(per_frame_ssim_lapis))
    overall_nse_shred = float(np.mean(per_frame_nse_shred))
    overall_nse_lapis = float(np.mean(per_frame_nse_lapis))
    overall_kge_prime_abs_shred = float(np.mean(per_frame_kge_prime_abs_shred))
    overall_kge_prime_abs_lapis = float(np.mean(per_frame_kge_prime_abs_lapis))

    gt_range = float(test_dod.max() - test_dod.min())

    # Attach to metrics dicts for downstream
    for prefix, m, vals in [
        ('shred', metrics_shred,
         (overall_nrmse_shred, overall_ssim_shred, per_frame_nrmse_shred, per_frame_ssim_shred,
          overall_nse_shred, per_frame_nse_shred,
          overall_kge_prime_abs_shred,
          per_frame_kge_prime_abs_shred)),
        ('lapis', metrics_lapis,
         (overall_nrmse_lapis, overall_ssim_lapis, per_frame_nrmse_lapis, per_frame_ssim_lapis,
          overall_nse_lapis, per_frame_nse_lapis,
          overall_kge_prime_abs_lapis,
          per_frame_kge_prime_abs_lapis)),
    ]:
        (on, os, pfn, pfs, onse, pfnse,
         okpa, pfkpa) = vals
        m['overall_nrmse_active'] = on
        m['overall_ssim'] = os
        m['per_frame_nrmse'] = pfn
        m['per_frame_ssim'] = pfs
        m['overall_nse'] = onse
        m['per_frame_nse'] = pfnse
        m['overall_kge_prime_abs'] = okpa
        m['per_frame_kge_prime_abs'] = pfkpa
        m['gt_range'] = gt_range

    print(f"\n  GT range (all frames): [{test_dod.min():.4f}, {test_dod.max():.4f}], "
          f"Δ={gt_range:.4f}")
    print(f"\n  Forward SHRED Results (uses full sensor time series):")
    print(f"    Active RMSE:     {metrics_shred['rmse_active']:.4f} m")
    print(f"    Overall NRMSE:   {overall_nrmse_shred:.4f}")
    print(f"    Active Corr:     {metrics_shred['corr_active']:.4f}")
    print(f"    Overall SSIM:    {overall_ssim_shred:.4f}")
    print(f"    Overall NSE:     {overall_nse_shred:.4f}")
    print(f"    Overall KGE'|DoD|: {overall_kge_prime_abs_shred:.4f}")

    lapis_label = (f"LAPIS Forward Results (uses first {obs_len} frames)" if use_forward
                   else "LAPIS Backward Results (uses ONLY terminal frame)")
    print(f"\n  {lapis_label}:")
    print(f"    Active RMSE:     {metrics_lapis['rmse_active']:.4f} m")
    print(f"    Overall NRMSE:   {overall_nrmse_lapis:.4f}")
    print(f"    Active Corr:     {metrics_lapis['corr_active']:.4f}")
    print(f"    Overall SSIM:    {overall_ssim_lapis:.4f}")
    print(f"    Overall NSE:     {overall_nse_lapis:.4f}")
    print(f"    Overall KGE'|DoD|: {overall_kge_prime_abs_lapis:.4f}")
    timer.stop("6. LAPIS inference")

    # Step 7: Save results
    print("\n[7] Saving Results...")
    timer.start("7. Saving results")

    save_ensemble_results(
        test_dod, pred_lapis, combined_active,
        test_theta, metrics_lapis,
        config, config.RESULTS_DIR / "lapis_ensemble_results.png")
    save_ensemble_results_logscale(
        test_dod, pred_lapis, combined_active, sensors,
        train_thetas, test_theta, metrics_lapis,
        config, config.RESULTS_DIR / "lapis_ensemble_results_logscale.png")
    save_ensemble_results_logscale(
        test_dod, pred_lapis, combined_active, sensors,
        train_thetas, test_theta, metrics_lapis,
        config, config.RESULTS_DIR / "lapis_ensemble_results_logscale_3col.png",
        n_columns=3)
    save_shred_results_logscale(
        test_dod, pred_shred, combined_active, sensors,
        train_thetas, test_theta, metrics_shred,
        config, config.RESULTS_DIR / "shred_ensemble_results_logscale.png")
    save_error_distribution_plot(
        test_dod, pred_lapis, pred_shred, combined_active, config,
        config.RESULTS_DIR / "error_distribution_last_frame.png", use_log_y=True)
    save_error_distribution_plot(
        test_dod, pred_lapis, pred_shred, combined_active, config,
        config.RESULTS_DIR / "error_distribution_last_frame_linear.png", use_log_y=False)

    metrics_data = {
        'version': 'lapis_landslide',
        'inference_mode': config.INFERENCE_MODE,
        'obs_len': obs_len,
        'scenario': config.SCENARIO_TAG,
        'location': config.LOCATION,
        'year': config.YEAR,
        'fixed_mwr_tag': config.FIXED_MWR_TAG,
        'climate_class': config.CLIMATE_CLASS,
        'theta_group': config.THETA_GROUP,
        'description': config.METADATA.get('description', ''),
        'train_thetas': train_thetas,
        'test_theta': test_theta,
        'gt_range_all_frames': gt_range,
        'metrics_shred': {
            'rmse_active': metrics_shred['rmse_active'],
            'corr_active': metrics_shred['corr_active'],
            'overall_nrmse_active': overall_nrmse_shred,
            'overall_ssim': overall_ssim_shred,
            'per_frame_nrmse': per_frame_nrmse_shred,
            'per_frame_ssim': per_frame_ssim_shred,
            'overall_nse': overall_nse_shred,
            'per_frame_nse': per_frame_nse_shred,
            'overall_kge_prime_abs': overall_kge_prime_abs_shred,
            'per_frame_kge_prime_abs': per_frame_kge_prime_abs_shred,
        },
        'metrics_lapis': {
            'rmse_active': metrics_lapis['rmse_active'],
            'corr_active': metrics_lapis['corr_active'],
            'overall_nrmse_active': overall_nrmse_lapis,
            'overall_ssim': overall_ssim_lapis,
            'per_frame_nrmse': per_frame_nrmse_lapis,
            'per_frame_ssim': per_frame_ssim_lapis,
            'overall_nse': overall_nse_lapis,
            'per_frame_nse': per_frame_nse_lapis,
            'overall_kge_prime_abs': overall_kge_prime_abs_lapis,
            'per_frame_kge_prime_abs': per_frame_kge_prime_abs_lapis,
        },
        'timestamp': datetime.now().isoformat()
    }
    json_path = config.RESULTS_DIR / "lapis_metrics.json"
    with open(json_path, 'w') as f:
        json.dump(metrics_data, f, indent=2)
    print(f"  Saved: {json_path}")

    update_summary_metrics(config, metrics_shred, metrics_lapis,
                           train_thetas, test_theta, T_test)
    timer.stop("7. Saving results")

    # Step 8: Animations
    print("\n[8] Generating Animations...")
    timer.start("8. Animations & figures")
    if config.GENERATE_VIDEOS:
        print("  (Video generation ENABLED)")
    else:
        print("  (Video generation DISABLED — GIF only)")

    save_video(test_dod, pred_lapis, combined_active, sensors, config,
               config.RESULTS_DIR / "lapis", "lapis_ensemble")
    save_video_logscale(test_dod, pred_lapis, combined_active, sensors, config,
                        config.RESULTS_DIR / "lapis", "lapis_ensemble_logscale")

    # Step 9: Zoomed frame figures
    print("\n[9] Generating Zoomed Frame Figures...")

    ensemble_frame = 1
    tag = f"LAPIS ({config.CLIMATE_CLASS}/{config.THETA_GROUP})"
    save_zoomed_frame_figure(
        test_dod, pred_lapis, combined_active, ensemble_frame, tag, config,
        config.RESULTS_DIR / "lapis_ensemble_zoomed_frame1.png")
    save_zoomed_frame_figure_logscale(
        test_dod, pred_lapis, combined_active, ensemble_frame, tag, config,
        config.RESULTS_DIR / "lapis_ensemble_zoomed_frame1_logscale.png")

    lapis_metrics_frame1 = compute_metrics(
        pred_lapis[ensemble_frame:ensemble_frame + 1],
        test_dod[ensemble_frame:ensemble_frame + 1],
        combined_active)
    save_combined_results_plot(
        test_dod[ensemble_frame], pred_lapis[ensemble_frame],
        combined_active, sensors, train_thetas, test_theta,
        lapis_metrics_frame1, config,
        config.RESULTS_DIR / "lapis_combined_frame1.png",
        title_prefix=f"LAPIS {'Forward' if use_forward else 'Backward'}")
    save_combined_results_plot_logscale(
        test_dod[ensemble_frame], pred_lapis[ensemble_frame],
        combined_active, sensors, train_thetas, test_theta,
        lapis_metrics_frame1, config,
        config.RESULTS_DIR / "lapis_combined_frame1_logscale.png",
        title_prefix=f"LAPIS {'Forward' if use_forward else 'Backward'} (Log Scale)")

    # Complete!
    timer.stop("8. Animations & figures")
    timer.print_summary()

    print("\n" + "=" * 70)
    print("  LAPIS Landslide — Training & Evaluation Complete!")
    print("=" * 70)
    print(f"\n  Scenario: {config.SCENARIO_TAG}")
    print(f"  Inference mode: {config.INFERENCE_MODE}")
    if use_forward:
        print(f"  Observation window: {obs_len} frames")
    print(f"  Results saved to: {config.RESULTS_DIR}/")
    print(f"  Session log: {log_path.name}")
    print("=" * 70)

    # ---- Close session log ----
    log_f.close()
    sys.stdout = sys.__stdout__
    sys.stderr = sys.__stderr__


# CLI / ENTRY POINT

def main():
    parser = argparse.ArgumentParser(
        description="LAPIS-SHRED Landslide — Spatiotemporal Reconstruction",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Note: When run without CLI arguments, uses RunConfig at the top of the file.
"""
    )
    parser.add_argument("--location", default=None)
    parser.add_argument("--year", default=None)
    parser.add_argument("--fixed_mwr_tag", default=None)
    parser.add_argument("--climate_class", default=None)
    parser.add_argument("--theta_group", default=None)
    parser.add_argument("--generate_videos", action="store_true", default=False)
    parser.add_argument("--inference_mode", type=str, default=None,
                        choices=["forward", "backward"],
                        help="LAPIS direction: 'backward' (default) or 'forward'")

    args = parser.parse_args()

    no_cli = (args.location is None and args.climate_class is None
              and args.theta_group is None)

    if no_cli:
        print("  (No CLI args — using RunConfig from script header)")
        location = RunConfig.LOCATION
        year = RunConfig.YEAR
        fixed_mwr_tag = RunConfig.FIXED_MWR_TAG
        climate_class = RunConfig.CLIMATE_CLASS
        theta_group = RunConfig.THETA_GROUP
        generate_videos = RunConfig.GENERATE_VIDEOS
    else:
        if not all([args.location, args.climate_class, args.theta_group]):
            parser.error("--location, --climate_class, and --theta_group are required")
        location = args.location
        year = args.year or RunConfig.YEAR
        fixed_mwr_tag = args.fixed_mwr_tag or RunConfig.FIXED_MWR_TAG
        climate_class = args.climate_class
        theta_group = args.theta_group
        generate_videos = args.generate_videos

