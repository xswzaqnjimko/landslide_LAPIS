def load_simulation(sim_dir: Path) -> Dict[int, np.ndarray]:
    """Load simulation from a directory of .npy files."""
    if not (sim_dir / 'iter_0000.npy').exists():
        raise FileNotFoundError(f"Simulation not found: {sim_dir}")
    return {int(f.stem.split('_')[1]): np.load(f)
            for f in sorted(sim_dir.glob("iter_*.npy"))}


def evolution_to_dod(evolution: Dict[int, np.ndarray]) -> np.ndarray:
    """Convert evolution dict to DoD array (T, H, W)."""
    iterations = sorted(evolution.keys())
    elevation = np.stack([evolution[i] for i in iterations])
    return elevation - elevation[0:1]


def crop_stagnation(dod: np.ndarray, window: int,
                    threshold: float = 0.1) -> np.ndarray:
    """Crop trailing frames where the landslide boundary has stopped expanding."""
    T = dod.shape[0]
    if window <= 0 or T <= window:
        return dod

    prev_boundary = np.abs(dod[0]) > threshold
    streak = 0

    for t in range(1, T):
        curr_boundary = np.abs(dod[t]) > threshold
        new_cells = curr_boundary & ~prev_boundary
        if new_cells.sum() <= 2: # newly activated cells; adjust as needed
            streak += 1
            if streak >= window:
                stop = t - window + 1
                return dod[:stop + 1]
        else:
            streak = 0
        prev_boundary = curr_boundary

    return dod


def load_all_simulations(config: Config) -> Tuple[List[np.ndarray], np.ndarray, Optional[List[int]]]:
    """Load all training and test simulations."""
    train_dods = []
    sim_dir = config.SIM_DIR
    stag_win = getattr(config, 'STAGNATION_WINDOW', 0) or 0

    sim_dirs_found = sorted(
        [d for d in sim_dir.iterdir()
         if d.is_dir() and d.name.startswith("sim_theta_")],
        key=lambda d: d.name
    )

    for sd in sim_dirs_found:
        evo = load_simulation(sd)
        dod = evolution_to_dod(evo)
        T_orig = dod.shape[0]
        if stag_win > 0:
            dod = crop_stagnation(dod, stag_win, config.ACTIVE_THRESHOLD)
        train_dods.append(dod)
        crop_info = f" → {dod.shape[0]} after crop" if dod.shape[0] < T_orig else ""
        print(f"      {sd.name}: {T_orig} steps{crop_info}, "
              f"DoD range [{dod.min():.2f}, {dod.max():.2f}]")

    if len(train_dods) == 0:
        raise FileNotFoundError(f"No training simulations found in {sim_dir}")

    gt_path = sim_dir / "ground_truth"
    if not gt_path.exists():
        raise FileNotFoundError(f"Ground truth not found: {gt_path}")

    gt_evo = load_simulation(gt_path)
    test_dod = evolution_to_dod(gt_evo)
    T_orig_gt = test_dod.shape[0]
    if stag_win > 0:
        test_dod = crop_stagnation(test_dod, stag_win, config.ACTIVE_THRESHOLD)
    crop_info = f" → {test_dod.shape[0]} after crop" if test_dod.shape[0] < T_orig_gt else ""
    print(f"      ground_truth: {T_orig_gt} steps{crop_info}, "
          f"DoD range [{test_dod.min():.2f}, {test_dod.max():.2f}]")

    # GT-anchored length filtering
    length_factor = getattr(config, 'SIM_LENGTH_FACTOR', 0) or 0
    keep_indices = None
    if length_factor > 0 and len(train_dods) > 1:
        gt_len = test_dod.shape[0]
        lo = gt_len / length_factor
        hi = gt_len * length_factor
        lengths = [d.shape[0] for d in train_dods]
        keep = [i for i, L in enumerate(lengths) if lo <= L <= hi]

        if len(keep) < len(train_dods) and len(keep) >= 3:
            dropped = [i for i in range(len(train_dods)) if i not in keep]
            for i in dropped:
                print(f"      DROPPED sim_theta_{i:02d}: {lengths[i]} steps "
                      f"(outside [{lo:.0f}, {hi:.0f}] = GT {gt_len} × "
                      f"[1/{length_factor}, {length_factor}])")
            train_dods = [train_dods[i] for i in keep]
            keep_indices = keep
            print(f"      Kept {len(keep)}/{len(lengths)} training simulations")
        elif len(keep) < 3:
            print(f"      WARNING: length filter would keep only {len(keep)} sims "
                  f"(need ≥3), skipping filter")

    return train_dods, test_dod, keep_indices


# SENSOR PLACEMENT

def place_sensors(dem: np.ndarray, dod: np.ndarray, n_sensors: int,
                  threshold: float = 0.1, seed: int = 42) -> np.ndarray:
    """Place sensors."""
    H, W = dem.shape
    rng = np.random.RandomState(seed)

    valid = np.ones((H, W), dtype=bool)
    valid[:2, :] = valid[-2:, :] = valid[:, :2] = valid[:, -2:] = False
    valid[np.isnan(dem)] = False

    sensors = []
    active = np.abs(dod) > threshold
    active_idx = np.where(active.ravel())[0]

    if len(active_idx) > 0:
        n_active = min(int(0.6 * n_sensors), len(active_idx))
        weights = np.abs(dod.ravel()[active_idx])
        weights /= weights.sum() + 1e-8

        for idx in rng.choice(active_idx, n_active, replace=False, p=weights):
            r, c = idx // W, idx % W
            if valid[r, c]:
                sensors.append([r, c])
                valid[r, c] = False

    n_remaining = n_sensors - len(sensors)
    if n_remaining > 0:
        remaining_idx = np.where(valid.ravel())[0]
        if len(remaining_idx) > 0:
            dy, dx = np.gradient(np.nan_to_num(dem, nan=0.0))
            slope = np.sqrt(dx ** 2 + dy ** 2).ravel()
            weights = slope[remaining_idx] + 0.01
            weights /= weights.sum()

            for idx in rng.choice(remaining_idx, min(n_remaining, len(remaining_idx)),
                                  replace=False, p=weights):
                sensors.append([idx // W, idx % W])

    return np.array(sensors)


