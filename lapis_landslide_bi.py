def load_esri_ascii(filepath: Path) -> Tuple[np.ndarray, dict]:
    """Load ESRI ASCII grid file."""
    with open(filepath) as f:
        meta = {}
        for _ in range(6):
            parts = f.readline().strip().split()
            if len(parts) >= 2:
                key = parts[0].lower()
                try:
                    meta[key] = (int(float(parts[1]))
                                 if key in ('ncols', 'nrows')
                                 else float(parts[1]))
                except ValueError:
                    meta[key] = parts[1]
        if 'nodata_value' not in meta:
            meta['nodata_value'] = -9999
        data = np.array([[float(x) for x in line.split()]
                         for line in f if line.strip()])
    return data, meta


def load_topology(config: Config) -> Dict:
    """Load topology data for current scenario."""
    dem, meta = load_esri_ascii(config.TOPOLOGY_DIR / 'dem.asc')
    nodata = meta.get('nodata_value', -9999)

    poly, _ = load_esri_ascii(config.TOPOLOGY_DIR / 'landslide_polygon.asc')
    poly[poly == nodata] = 0
    depth, _ = load_esri_ascii(config.TOPOLOGY_DIR / 'landslide_depth.asc')
    depth[depth == nodata] = 0

    nodata_mask = (dem == nodata)
    if nodata_mask.any():
        dem[nodata_mask] = np.nan
        print(f"  Masked {nodata_mask.sum()} NODATA cells in DEM as NaN")

    return {'dem': dem, 'meta': meta, 'polygon': (poly > 0).astype(int),
            'depth': depth, 'nodata_mask': nodata_mask}


